#!/usr/bin/env bash
# Runtime regression test for WYRM-07.
#
# The self-hosted compiler emits target-independent LLVM IR (opaque pointers and
# scalar calls into the C runtime). This test proves that a target-less module of
# that shape is accepted by clang, that clang infers the host triple/data layout
# instead of a hard-coded Windows one, and that the resulting binary runs.
set -u

if ! command -v clang >/dev/null 2>&1; then
    printf 'SKIP: clang is not available; WYRM-07 static coverage is in test_install_static.sh\n'
    exit 0
fi

PASS_COUNT=0
FAIL_COUNT=0

pass_case() {
    PASS_COUNT=$((PASS_COUNT + 1))
    printf 'PASS: %s\n' "$1"
}

fail_case() {
    FAIL_COUNT=$((FAIL_COUNT + 1))
    printf 'FAIL: %s\n' "$1"
}

check_true() {
    local label=$1
    shift
    if "$@"; then
        pass_case "$label"
    else
        fail_case "$label"
    fi
}

WORK_DIR=$(mktemp -d)
trap 'rm -rf "$WORK_DIR"' EXIT

cat > "$WORK_DIR/runtime.c" <<'EOF'
#include <stdio.h>
typedef struct { int tag; union { double number; } value; } Value;
void llvm_val_number(Value *slot, double number) {
    (void)slot;
    printf("llvm_val_number: %.1f\n", number);
}
EOF

# Mirrors the structure emitted by transpile_llvm(): target-independent
# aggregate types, opaque pointers, and a call into the C runtime. No target
# datalayout or target triple lines are present.
cat > "$WORK_DIR/module.ll" <<'EOF'
; Module generated by Wyrm 1.2.1 Self-Hosted LLVM backend
%struct.Value = type { i32, %union.anon }
%union.anon = type { double }

declare void @llvm_val_number(ptr, double)

define i32 @main() {
entry:
  %slot = alloca %struct.Value, align 8
  call void @llvm_val_number(ptr %slot, double 42.0)
  ret i32 0
}
EOF

if clang -S -emit-llvm -o "$WORK_DIR/inferred.ll" "$WORK_DIR/module.ll" 2>"$WORK_DIR/infer.err"; then
    pass_case 'WYRM-07 clang accepts target-less IR'
else
    fail_case 'WYRM-07 clang accepts target-less IR'
    cat "$WORK_DIR/infer.err" >&2
fi

INFERRED_TRIPLE=$(grep -m1 'target triple = ' "$WORK_DIR/inferred.ll" 2>/dev/null || true)
INFERRED_LAYOUT=$(grep -m1 'target datalayout = ' "$WORK_DIR/inferred.ll" 2>/dev/null || true)

case "$INFERRED_TRIPLE" in
    *'target triple'*) pass_case 'WYRM-07 clang emits an inferred target triple' ;;
    *) fail_case 'WYRM-07 clang emits an inferred target triple' ;;
esac
case "$INFERRED_TRIPLE" in
    *windows*) fail_case 'WYRM-07 inferred triple is not the hard-coded Windows triple' ;;
    *) pass_case 'WYRM-07 inferred triple is not the hard-coded Windows triple' ;;
esac
case "$INFERRED_LAYOUT" in
    *'target datalayout'*) pass_case 'WYRM-07 clang emits a matching data layout' ;;
    *) fail_case 'WYRM-07 clang emits a matching data layout' ;;
esac
case "$INFERRED_LAYOUT" in
    *'e-m:w-'*) fail_case 'WYRM-07 inferred data layout is not the Windows layout' ;;
    *) pass_case 'WYRM-07 inferred data layout is not the Windows layout' ;;
esac

if clang -O2 "$WORK_DIR/module.ll" "$WORK_DIR/runtime.c" -o "$WORK_DIR/targetless_test" 2>"$WORK_DIR/link.err"; then
    pass_case 'WYRM-07 clang links target-less IR with C runtime'
else
    fail_case 'WYRM-07 clang links target-less IR with C runtime'
    cat "$WORK_DIR/link.err" >&2
fi

if [ -x "$WORK_DIR/targetless_test" ]; then
    OUTPUT=$("$WORK_DIR/targetless_test" 2>/dev/null)
    RC=$?
    if [ "$RC" -eq 0 ]; then
        pass_case 'WYRM-07 resulting binary runs'
    else
        fail_case 'WYRM-07 resulting binary runs'
    fi
    if [ "$OUTPUT" = 'llvm_val_number: 42.0' ]; then
        pass_case 'WYRM-07 C runtime call observes the expected value'
    else
        fail_case 'WYRM-07 C runtime call observes the expected value'
    fi
else
    fail_case 'WYRM-07 resulting binary runs'
    fail_case 'WYRM-07 C runtime call observes the expected value'
fi

printf '\nTOTAL: %d passed, %d failed\n' "$PASS_COUNT" "$FAIL_COUNT"
[ "$FAIL_COUNT" -eq 0 ]
